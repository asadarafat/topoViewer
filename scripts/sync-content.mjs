import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import yaml from 'js-yaml';
import { exampleFileKeys, sourceFileFor } from './lib/content-examples.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = path.join(repoRoot, 'packages/topoviewer');
const contentRoot = path.join(packageRoot, 'content');
const contentPagesRoot = path.join(contentRoot, 'pages');
const contentExamplesRoot = path.join(contentRoot, 'examples');
const contentFragmentsRoot = path.join(contentPagesRoot, '_fragments');
const packageDocsRoot = path.join(packageRoot, 'docs');
const packageExamplesRoot = path.join(packageRoot, 'examples');
const packageTestCasesRoot = path.join(packageExamplesRoot, 'test-cases');
const packageStressRoot = path.join(packageExamplesRoot, 'stress');
const docsRoot = path.resolve(process.env.TOPOVIEWER_DOCS_ROOT || path.join(repoRoot, 'docs'));
const checkOnly = process.argv.includes('--check');
const allowDirtyProjectionOverwrite = process.env.TOPOVIEWER_SYNC_ALLOW_DIRTY_PROJECTIONS === '1';

function readText(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function readYaml(filePath) {
  return yaml.load(readText(filePath)) || {};
}

function dumpYaml(document) {
  return yaml.dump(document, {
    lineWidth: 120,
    noRefs: true,
    quotingType: '"'
  });
}

function toPosix(value) {
  return value.split(path.sep).join(path.posix.sep);
}

function relative(filePath) {
  return toPosix(path.relative(repoRoot, filePath));
}

function fail(message) {
  console.error(message);
  process.exitCode = 1;
}

function writeTextIfChanged(filePath, content) {
  const existing = fs.existsSync(filePath) ? readText(filePath) : undefined;
  if (existing === content) return false;
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
  return true;
}

function isGitDirty(filePath) {
  try {
    const output = execFileSync('git', ['status', '--porcelain', '--', path.relative(repoRoot, filePath)], {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore']
    });
    return output.trim().length > 0;
  } catch {
    return false;
  }
}

function assertProjectionCanBeOverwritten(filePath, content, label, source) {
  if (checkOnly || allowDirtyProjectionOverwrite || !source || !fs.existsSync(filePath)) return;
  if (readText(filePath) === content) return;
  if (!isGitDirty(filePath) || isGitDirty(source)) return;

  throw new Error([
    `Refusing to overwrite dirty generated content projection: ${relative(filePath)}`,
    `Projection: ${label}`,
    `Canonical source: ${relative(source)}`,
    '',
    'Edit the canonical source under packages/topoviewer/content/**, then run:',
    '  npm run sync:docs',
    '',
    'If this projected file was changed by mistake, revert or discard that generated-file edit first.',
    'To force regeneration anyway, rerun with TOPOVIEWER_SYNC_ALLOW_DIRTY_PROJECTIONS=1.'
  ].join('\n'));
}

function projectText(filePath, content, label, source) {
  if (checkOnly) {
    const existing = fs.existsSync(filePath) ? readText(filePath) : undefined;
    if (existing !== content) {
      fail(`${label} is out of sync: ${relative(filePath)}`);
    }
    return false;
  }

  assertProjectionCanBeOverwritten(filePath, content, label, source);
  if (writeTextIfChanged(filePath, content)) {
    console.log(`generated ${relative(filePath)}`);
    return true;
  }
  return false;
}

function listFiles(dirPath) {
  if (!fs.existsSync(dirPath)) return [];
  const files = [];
  for (const entry of fs.readdirSync(dirPath, { withFileTypes: true })) {
    const absolute = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      files.push(...listFiles(absolute));
    } else if (entry.isFile()) {
      files.push(absolute);
    }
  }
  return files;
}

function removeStaleFiles(root, expectedFiles, label) {
  const expected = new Set([...expectedFiles].map((filePath) => path.resolve(filePath)));
  for (const filePath of listFiles(root)) {
    if (expected.has(path.resolve(filePath))) continue;
    if (checkOnly) {
      fail(`${label} has stale generated file: ${relative(filePath)}`);
    } else {
      fs.rmSync(filePath);
      console.log(`removed stale ${relative(filePath)}`);
    }
  }
}

function fragment(name) {
  return readText(path.join(contentFragmentsRoot, name)).trim();
}

function generatedNotice(source) {
  return `<!-- Generated from ${source}. Do not edit this file directly. -->`;
}

