import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

export const requiredDemoFixtureIds = [
  'layered-network',
  'clos-2spine-4leaf',
  'insert-workflow',
  'attention-workflow',
  'inspector-workflow',
  'dense-links'
];

export function repoRootFromScripts() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
}

export function contentExamplesRoot(repoRoot = repoRootFromScripts()) {
  return path.join(repoRoot, 'packages/topoviewer/content/examples');
}

export function grafanaGeneratedFixturePath(repoRoot = repoRootFromScripts()) {
  return path.join(repoRoot, 'packages/grafana-topoviewer-panel/src/generated/demoFixtures.ts');
}

function toPosix(relativePath) {
  return relativePath.split(path.sep).join('/');
}

function catalogPath(repoRoot) {
  return path.join(contentExamplesRoot(repoRoot), 'catalog.yaml');
}

function fixtureMetadata(example) {
  if (!example.fixture) return undefined;
  return typeof example.fixture === 'object' ? example.fixture : {};
}

function exampleSourceFile(repoRoot, example, key) {
  const root = contentExamplesRoot(repoRoot);
  const fileName = key === 'topology' ? 'topology.yaml' : 'stylesheet.yaml';
  const configured = example.sourceFiles?.[key];
  const source = path.join(root, configured || example.sourcePath || example.path, fileName);
  const relativePath = path.relative(root, source);
  if (relativePath.startsWith('..') || path.isAbsolute(relativePath)) {
    throw new Error(`Demo fixture source resolves outside canonical content examples: ${source}`);
  }
  return source;
}

export function loadGrafanaDemoFixtureSources(repoRoot = repoRootFromScripts()) {
  const sourceCatalog = catalogPath(repoRoot);
  if (!fs.existsSync(sourceCatalog)) {
    throw new Error(`Canonical content catalog is missing: ${sourceCatalog}`);
  }

  const catalog = yaml.load(fs.readFileSync(sourceCatalog, 'utf8'));
  const fixtureIds = new Set();
  const fixtures = (catalog?.examples || [])
    .flatMap((example) => {
      const metadata = fixtureMetadata(example);
      if (!metadata) return [];

      const fixture = {
        id: metadata.id || example.id,
        name: metadata.name || example.title,
        order: metadata.order ?? Number.MAX_SAFE_INTEGER,
        topologyFile: exampleSourceFile(repoRoot, example, 'topology'),
        stylesheetFile: exampleSourceFile(repoRoot, example, 'stylesheet')
      };

      if (fixtureIds.has(fixture.id)) {
        throw new Error(`Duplicate demo fixture id in canonical catalog: ${fixture.id}`);
      }
      fixtureIds.add(fixture.id);
      return [fixture];
    })
    .sort((left, right) => left.order - right.order || left.name.localeCompare(right.name) || left.id.localeCompare(right.id));

  for (const requiredId of requiredDemoFixtureIds) {
    if (!fixtureIds.has(requiredId)) {
      throw new Error(`Required demo fixture is missing from canonical catalog: ${requiredId}`);
    }
  }

  return fixtures;
}

export function loadGrafanaDemoFixtures(repoRoot = repoRootFromScripts()) {
  const root = contentExamplesRoot(repoRoot);
  return loadGrafanaDemoFixtureSources(repoRoot).map((fixture) => ({
    id: fixture.id,
    name: fixture.name,
    order: fixture.order,
    source: {
      topology: toPosix(path.relative(root, fixture.topologyFile)),
      stylesheet: toPosix(path.relative(root, fixture.stylesheetFile))
    },
    topologyYaml: fs.readFileSync(fixture.topologyFile, 'utf8'),
    stylesheetYaml: fs.readFileSync(fixture.stylesheetFile, 'utf8')
  }));
}

export function renderGrafanaDemoFixturesModule(repoRoot = repoRootFromScripts()) {
  const fixtures = loadGrafanaDemoFixtures(repoRoot);
  return `// Generated by scripts/sync-grafana-demo-fixtures.mjs. Do not edit by hand.
import type { GrafanaDemoFixture } from '../types';

export const demoFixtures = ${JSON.stringify(fixtures, null, 2)} satisfies GrafanaDemoFixture[];
`;
}
